/*
 * legendre_polynomials.c —— 求 n 阶勒让德多项式 P_n(x) 的值（递归）
 * 来源：《C程序设计》第七章 习题（用递归方法求 n 阶勒让德多项式的值）
 * 日期：2026-11-24
 * 思路：1) 题面直接给了递推式：P_0 = 1、P_1 = x，之后每一项都由前两项算出来。
 *          这是最典型的「递归三件套」——什么时候停、怎么由小的推大的、
 *          参数怎么往「停」的方向缩小。
 *       2) 递归版照着公式抄就行，难点不在算法，而在别抄漏符号（见坑 1）。
 *       3) 递归会重复算：P_{n-1} 和 P_{n-2} 各自展开成一棵树，同一个 P_k 被算很多遍。
 *          实测调用次数 n=10 是 177 次、n=20 是 21891 次、n=32 是 7049155 次，
 *          每加 2 乘 2.618（黄金比的平方），是指数增长。
 *       4) 所以实际工程里会改成迭代：只留 p0、p1 两个格子，从 k = 2 推到 n，
 *          O(n) 时间、O(1) 空间（代码见建议 1）。
 * 要点：递归三件套 —— 终止条件（n == 0 / n == 1）、递推式、参数缩小（n-1、n-2）。
 *       函数声明写在 main 里是合法的，但放在文件顶部、或干脆把定义放到 main 前面更好找；
 *       本文件用的是「定义在前」，所以一行声明都不需要。
 * 坑：1) 第一版漏了一个乘号：
 *             ((2*n-1) * x - legendre(n-1,x) - (n-1) * legendre(n-2,x)) / n
 *          正确的是 (2n-1) * x * P_{n-1}(x)，x 后面那个 legendre 必须乘上去，
 *          漏了算出来就是个完全不同的多项式 —— 但语法、类型全对，gcc 一声不吭。
 *          证据：n=2, x=0.5 应为 -0.125，错版给 0.00；n=3, x=0.5 应为 -0.4375，错版给 0.50
 *       2) 最快的自查不是对拍，是代特殊值：勒让德多项式恒有 P_n(1) = 1。
 *          错版在 x=1 时给出 0.5 / 0.833 / 1.167 / 0.9 …… 一眼就露了
 *       3) 输入提示语「请输入n,x:」在教材作业里没问题，
 *          但要交给判题机必须删掉，否则多一行输出、逐字节比对直接错
 * 建议：1) 等价的迭代版，O(n)：
 *              double p0 = 1.0, p1 = x, p2 = 0;
 *              for (int k = 2; k <= n; k++) {
 *                  p2 = ((2 * k - 1) * x * p1 - (k - 1) * p0) / k;
 *                  p0 = p1; p1 = p2;
 *              }
 *              return p1;
 *          本文件原有两个版本（递归版 legendre_1、迭代版 legendre_2），
 *          整理时只留递归版当教材答案，迭代版挪到这里当参考。
 *       2) 想保留递归结构又不想指数爆炸，加一张记忆化表 cache[n]：
 *          算过就查表，O(2^n) 降到 O(n)。
 */
#include <stdio.h>

double legendre(int n, double x)
{
    if (n == 0)
        return 1.0;
    else if (n == 1)
        return x;
    else
        return ((2 * n - 1) * x * legendre(n - 1, x) - (n - 1) * legendre(n - 2, x)) / n;
}

int main()
{
    int n;
    double x;
    printf("请输入n,x:\n");
    if (scanf("%d %lf", &n, &x) != 2)
        return 1;
    printf("%f\n", legendre(n, x));
    return 0;
}
