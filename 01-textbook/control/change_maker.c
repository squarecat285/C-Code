/*
 * change_maker.c —— 找零机：算出该找多少钱，以及用哪几张面额
 * 来源：自己想做的（《C程序设计》第三章 顺序结构 练习）
 * 日期：2026-10-14
 * 要点：用 / 取出张数、用 % 把余数传给下一种面额，从大到小逐个"剥"；
 *       scanf 有返回值必须检查，否则非法输入会打印内存垃圾或死循环
 */

#include <stdio.h>

int main()
{
    /* 必须给初值：scanf 失败时不会往变量里写，未初始化的局部变量就是内存垃圾 */
    int price = 0, pay = 0, change = 0;

    /* 反复询问，直到付款金额足够为止 */
    while (1)
    {
        printf("请输入应付金额 实付金额:");

        /* scanf 返回"成功读到的项数"。这里要读 2 个，返回值不是 2 就说明输入有误。
           输入 abc、或者输入流结束(EOF) 时它都会失败，必须在这里拦住：
           拦不住的话，变量保持原值会导致死循环，未初始化则打印垃圾数字 */
        if (scanf("%d %d", &price, &pay) != 2)
        {
            printf("输入无效，程序结束\n");
            return 1;
        }

        change = pay - price;
        if (change >= 0)
        {
            break; /* 钱够了，跳出循环去算明细 */
        }
        else
        {
            printf("实付金额不足，请重新输入\n");
        }
    }

    /* 从大到小逐个面额"剥"：
       / 算出这一档要几张，% 把剥剩下的余数交给下一档。
       例：63 -> 50元 1张，余 13；13 -> 10元 1张，余 3；3 -> 1元 3张 */
    int on_1 = change / 50; /* 50 元张数 */
    int on_2 = change % 50; /* 剥掉 50 后还剩多少 */
    int tw_1 = on_2 / 20;   /* 20 元张数 */
    int tw_2 = on_2 % 20;   /* 剥掉 20 后还剩多少 */
    int th_1 = tw_2 / 10;   /* 10 元张数 */
    int th_2 = tw_2 % 10;   /* 剥掉 10 后还剩多少 */
    int fo_1 = th_2 / 5;    /* 5 元张数 */
    int fo_2 = th_2 % 5;    /* 剩的全是 1 元，所以余数本身就是 1 元张数 */

    printf("应收: %d 元\n", price);
    printf("实收: %d 元\n", pay);
    printf("找零: %d 元\n", change);
    if (change == 0)
    {
        printf("无需找零\n");
    }
    else
    {
        printf("---找零明细---\n");

        /* 张数为 0 的面额不打印。每句 if 都带大括号：
           不带的话，以后往里面加第二行时，那一行不会被 if 管住 */
        if (on_1 != 0)
        {
            printf("50 元 * %d 张\n", on_1);
        }
        if (tw_1 != 0)
        {
            printf("20 元 * %d 张\n", tw_1);
        }
        if (th_1 != 0)
        {
            printf("10 元 * %d 张\n", th_1);
        }
        if (fo_1 != 0)
        {
            printf(" 5 元 * %d 张\n", fo_1);
        }
        if (fo_2 != 0)
        {
            printf(" 1 元 * %d 张\n", fo_2);
        }
    }

    return 0;
}
