/*
 * perfect_numbers.c —— 找出 1000 以内的所有完数（等于其因子之和的数）
 * 来源：《C程序设计》第五章 习题 9（原 01-textbook/3/9.c）
 * 日期：2026-10-27
 * 要点：因子只可能到 i / 2，所以内层循环写 j <= i / 2 就够，不用跑到 i。
 *       这题跑了两趟内层循环：第一趟只求 sum 用来判断，第二趟才打印因子 ——
 *       这样一趟求 sum、一趟打印，代码直白；也可以在第一趟里把因子存进数组，
 *       但那要多开一个数组，1000 以内没必要。
 *       逗号的处理：第一个因子前面不能有逗号，后面的都要 —— 用一个 first 标记，
 *       第一次进来不打印逗号，打完把 first 置 0。这比「判断是不是最后一个」简单，
 *       因为「最后一个」要在打印之前就知道，而第一次是不是第一个立刻就知道。
 * 坑：因子不包括自己。所以循环只到 i / 2，1 是唯一能进来的情况（1 的因子是 1，
 *     但 1 != 1 的因数和... 实际 1 不是完数，因为因数和是 0）。
 * 建议：内层那两个 if (i % j != 0) continue; 可以合起来写成 if (i % j == 0) { ... }，
 *       少一层缩进也更符合「能不加分支就不加」的直觉。
 *       输出用的是 %3d 而不是教材的 %d —— 让 6、28、496 右对齐成一列，
 *       所以每行前面会多 0~2 个空格。这是有意的对齐，不是多打了空格。
 */
#include <stdio.h>
int main()
{
    for (int i = 2; i <= 1000; i++)
    {
        int sum = 0;
        for (int j = 1; j <= i / 2; j++)
        {

            if (i % j != 0)
                continue;
            sum += j;
        }
        if (sum == i)
        {
            printf("%3d its factors are ", i);
            int first = 1;
            for (int j = 1; j <= i / 2; j++)
            {

                if (i % j != 0)
                    continue;
                if (!first)
                    printf(",");
                printf("%d", j);
                first = 0;
            }
            printf("\n");
        }
    }
    return 0;
}
