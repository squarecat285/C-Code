/*
 * 3.07_compare_with_limit.c —— 按第三个数选一个系数算出结果，再和上限比较，给两种表情
 * 来源：PTA 实验3 第 7 题
 * 日期：2026-11-24
 * 思路：1) 输入三个数里，第二个只是「开关」：等于 0 用一个系数，不等于 0 用另一个。
 *          用三目运算符一行就能表达，不必写 if / else。
 *       2) 算出来的数和第三个输入比大小，决定输出 T_T 还是 ^_^。
 * 要点：`t == 0 ? 2.455 : 1.26` —— 三目运算符适合这种「二选一」的取值。
 * 坑：`t` 被复用了两次：先当开关判断，再被赋成系数。原值就没了，
 *     如果后面还要用 t 就会错。这种「一个变量兼职两件事」是隐蔽 bug 的温床。
 * 建议：2.455 和 1.26 是魔法数字，起个名字（如 `factor_adult` / `factor_child`）会好读很多。
 */
#include <stdio.h>
int main()
{
    double a, t, b;
    scanf("%lf %lf %lf", &a, &t, &b);
    t = (t == 0 ? 2.455 : 1.26);
    printf("%.2f ", a * t);
    if (a * t > b)
        printf("T_T");
    else
        printf("^_^");
    return 0;
}
