/*
 * 3.06_days_in_month.c —— 给定年份和月份，输出这个月有多少天
 * 来源：PTA 实验3 第 6 题
 * 日期：2026-11-24
 * 思路：1) 12 个月里，31 天的有 7 个、30 天的有 4 个，只有 2 月看闰年 ——
 *          所以先把「31 天」的月份列全，2 月单独判，剩下的自然就是 30。
 *       2) 闰年规则：能被 4 整除但不能被 100 整除，或者能被 400 整除。
 * 要点：用「穷举特例 + else 兜底」处理分类，比写 12 个 case 短得多。
 * 建议：两处 `scanf` 都没检查返回值，输入坏掉时会拿着栈上的垃圾往下算。
 */
#include <stdio.h>
int main()
{
    int y;
    scanf("%d", &y);
    int a = 0;
    a = (y % 4 == 0 && y % 100 != 0) || (y % 400 == 0);
    int m;
    scanf("%d", &m);
    if (m == 1 || m == 3 || m == 5 || m == 7 || m == 8 || m == 10 || m == 12)
    {
        printf("31");
    }
    else if (m == 2)
    {
        if (a == 0)
            printf("28");
        else
            printf("29");
    }
    else
        printf("30");
    return 0;
}
