/*
 * 3.03_exactly_one_pass.c —— 两个人成绩，恰好一个人及格输出 1，否则输出 0
 * 来源：PTA 实验3 第 3 题
 * 日期：2026-11-24
 * 思路：1) 「恰好一个」有两种写法：一是「至少一个 且 不是两个都」，
 *          二是「a 及格 和 b 及格 这两个真假值不同」——后者更短。
 *       2) 两个 bool 值不同，就是 (a >= 60) != (b >= 60)。
 * 要点：`!(A && B) && (A || B)` 等价于 `A != B`（异或）。看到「恰好一个」先想异或。
 * 建议：`first` 这个名字读起来像「第一个」，其实是「结果」，改成 `only_one` 更清楚。
 */
#include <stdio.h>
int main()
{
    int a, b, first = 0;
    if (scanf("%d %d", &a, &b) != 2)
        return 1;
    if (!(a >= 60 && b >= 60) && (a >= 60 || b >= 60))
    {
        first = 1;
    }
    printf("%d", first);
    return 0;
}
