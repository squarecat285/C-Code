/*
 * L1-003_digit_count.c —— 个位数统计：数一个不超过 1000 位的正整数里每个数字出现几次
 * 来源：PTA 团体程序设计天梯赛-练习集 L1-003 个位数统计
 * 题目：pintia.cn → 题目集「团体程序设计天梯赛-练习集」→ L1-003
 * 日期：2026-10-24
 * 要点：开十个格子当计数器 int s[10] = {0}，扫一遍字符串，s[num[i] - '0']++ 就统计完了。
 *       输出时只列出现过的（s[i] != 0），顺序天然就是从 0 到 9。
 *       scanf("%s", num) 读一次就够，它会把整串读完并补 '\0'。
 * 坑：1) printf("%d:%c", i, s[i]) —— 用 %c 把「次数」当字符打，打出的是控制字符；
 *     2) if (s[i] - '0' != 0) —— 次数已经是数字了，再减 '0'（48）就变成负数，
 *        次数为 0 时 -48 != 0 成立，于是 0 次的数字也打印；
 *     3) for (i = 0; i < 9; i++) —— 少了 9，输入只有 "9" 时一个字都不输出；
 *     4) char s[10] 当计数器 —— char 上限 127，1000 个 '0' 溢出成 -24，打出 "0:-24"；
 *     5) for (i = 0; i < 1005; i++) s[num[i] - '0']++ —— 循环按数组大小跑而不是按
 *        字符串长度跑，越过 '\0' 后 0 - '0' = -48，往 s[-48] 越界写 999 次。
 *        原来用 switch 时没这个毛病，因为没匹配项就什么都不做；换成数组下标就没有这层保险了；
 *     6) for (i = 0; i < 1005; i++) scanf("%s", num) —— 想读 1005 次却只该读 1 次。
 *        管道输入喂完就 EOF 所以看不出来，在终端手打时第 2 次 scanf 会一直等 → 程序像卡死。
 * 教训：循环次数 = 数据有多少，不是数组开多大。
 */
#include <stdio.h>
int main()
{
    char num[1005] = {0};
    int s[10] = {0};
    scanf("%s", num);
    for (int i = 0; num[i] != '\0'; i++)
    {
        s[num[i] - '0']++;
    }

    for (int i = 0; i < 10; i++)
    {
        if (s[i] != 0)
        {
            printf("%d:%d", i, s[i]);
            printf("\n");
        }
    }
    return 0;
}
