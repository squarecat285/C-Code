/*
 * P3954_score.c —— 按 作业 20% + 小测 30% + 期末 50% 算出总成绩
 * 来源：洛谷 P3954 [NOIP 2017 普及组] 成绩
 * 题目：https://www.luogu.com.cn/problem/P3954
 * 结果：⬜ 待提交（本地 103 万组全对）
 * 日期：2026-10-17
 * 要点：百分比换成整数算 —— 先各乘 20 / 30 / 50 再整体除以 100，
 *       整数除法天然向下取整，不碰浮点就没有精度问题。
 * 坑：一开始写的是 int score = a * 0.2 + b * 0.3 + c * 0.5;
 *     两个样例都能过，但 0.3 在 double 里其实是 0.29999999999999998，
 *     a=1 b=6 c=0 时算出来 1.9999999999999998，(int) 一砍就是 1，
 *     正确答案是 2。103081 组答案是整数的数据里有 194 组会这样少 1。
 */
#include <stdio.h>
int main()
{
    int a, b, c;
    scanf("%d %d %d", &a, &b, &c);
    int score = (a * 20 + b * 30 + c * 50) / 100;
    printf("%d", score);
    return 0;
}
