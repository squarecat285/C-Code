/*
 * P5727_hailstone.c —— 冰雹猜想：奇数乘 3 加 1、偶数除以 2，一路到 1，再倒着输出
 * 来源：洛谷 P5727 【深基5.例3】冰雹猜想
 * 题目：https://www.luogu.com.cn/problem/P5727
 * 日期：2026-11-02
 * 思路：1) 从 n 开始一步步变，直到变成 1，每一步都要记下来 —— 因为最后要倒序输出。
 *       2) 先存再变：s[i] = n 必须在变换之前，否则 n 本身会丢。
 *       3) 变成 1 的那一步也要存进去（题目要从 1 开始倒着打），
 *          所以是先 s[i] = 1、发现 n == 1、然后才 break。
 *       4) 最后从 i 往回打到 0，第一个打出来的正好是 1。
 * 要点：n ≤ 100 时最长的链是 n = 97（118 步），所以 s[1000] 绰绰有余；
 *       中途最大会冲到 9232，int 装得下。
 * 坑：没有错。「1 也要存进数组」这一步最容易漏 —— 漏了就会从 2 开始打，少一个数。
 * 建议：循环体可以压平，去掉嵌套的 if/else：
 *       s[k++] = n;  if (n == 1) break;  n = (n % 2 == 0) ? n / 2 : 3 * n + 1;
 */
#include <stdio.h>
int main()
{
    int n;
    scanf("%d", &n);
    int i = 0;
    int s[1000];
    for (;; i++)
    {
        s[i] = n;
        if (n != 1)
        {
            if (n % 2 == 0)
                n = n / 2;
            else
                n = n * 3 + 1;
        }
        else
            break;
    }
    for (int j = i; j >= 0; j--)
    {
        printf("%d ", s[j]);
    }
    return 0;
}
