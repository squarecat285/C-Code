/*
 * P1428_cute_compare.c —— 小鱼比可爱：每只鱼回头看，有几只比它不可爱
 * 来源：洛谷 P1428 小鱼比可爱
 * 题目：https://www.luogu.com.cn/problem/P1428
 * 日期：2026-11-02
 * 思路：1) 每只鱼只看得见左边，所以读到第 i 只时，左边 i 只都已经读过了，
 *          可以边读边算，不用把输入全部读完再来一遍。
 *       2) 「有几只不如自己可爱」= 左边严格小于 a_i 的个数，内层扫 0 ~ i-1 数一下。
 *       3) 要回头比，前面的值就得留着，所以开数组存起来。
 *       4) 判断写 > 不能写 >=：题目说可爱程度可能一样，一样的不算「不如」。
 * 要点：第一只鱼左边没人，内层循环一次都不跑，count 自然是 0 —— 边界不用特判。
 * 坑：没有错。两个小地方：①int s[n] 是变长数组（C99 特性），gcc 能过，
 *     但它在栈上按 n 分配，n 一大就栈溢出，MSVC 更是完全不支持；
 *     ②每行末尾多打了一个空格，洛谷不介意，严格比对输出的题会介意。
 * 建议：a_i ≤ 10 是题目给的最大提示。开一个 int cnt[11]，每读一个 a，
 *       答案 = cnt[0] + cnt[1] + … + cnt[a-1]，然后 cnt[a]++。
 *       复杂度从 O(n²) 降到 O(11n)，这就是「用值域换时间」。
 */
#include <stdio.h>
int main()
{
    int n;
    scanf("%d", &n);
    int s[n];
    for (int i = 0; i < n; i++)
    {
        scanf("%d", &s[i]);
        int count = 0;
        for (int j = 0; j < i; j++)
        {
            if (s[i] > s[j])
            {
                count++;
            }
        }
        printf("%d ", count);
    }
    return 0;
}
