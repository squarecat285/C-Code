/*
 * P1047_tree_planting.c —— 校门外的树：马路上 L+1 个位置，挖掉若干区间后还剩几棵树
 * 来源：洛谷 P1047 [NOIP 2005 普及组] 校门外的树
 * 题目：https://www.luogu.com.cn/problem/P1047
 * 日期：2026-11-03
 * 思路：1) 每个位置只有「有树 / 没树」两种状态，一个 int 数组就能当一排开关。
 *       2) 先把 0 ~ L 全部拨到 1（有树），再把每个区间 [a, b] 逐格拨到 0。
 *       3) 最后数还剩几个 1 就是答案，不需要知道每棵树被挖了几次。
 *       4) 数的范围是 0 ~ len，不是 0 ~ 10000：len 之外不是马路，根本没有树。
 * 要点：0 号位置也算一个位置，所以马路上一共是 len + 1 个点，不是 len 个。
 *       区间是闭区间，内层写成 j = a; j <= b。
 * 坑：第一版计数写死成 i < +10000（那个 + 是一元加号，gcc 一声不吭），
 *     L = 10000 时会漏掉 10000 号那棵树；后来写 i <= 10000 又变成
 *     「靠 ={0} 初始化把 len 之外的空位排掉」才碰巧对。用数据边界收尾才算真对。
 * 建议：数据更大就该换差分数组：diff[a]++、diff[b+1]--，再求前缀和，
 *       前缀和为 0 的位置就是还活着的树，复杂度从 O(m·L) 降到 O(L + m)。
 *       二维版本（P1789 插火把、P5729 工艺品制作）用的是同一套写法。
 */
#include <stdio.h>
int main()
{
    int len;
    int arr[10005] = {0};
    scanf("%d", &len);
    for (int i = 0; i <= len; i++)
    {
        arr[i] = 1;
    }
    int n;
    scanf("%d", &n);
    for (int i = 0; i < n; i++)
    {
        int a, b;
        if (scanf("%d %d", &a, &b) != 2)
        {
            break;
        }
        for (int j = a; j <= b; j++)
        {
            arr[j] = 0;
        }
    }
    int count = 0;
    for (int i = 0; i <= len; i++)
    {
        if (arr[i] == 1)
        {
            count++;
        }
    }
    printf("%d", count);
    return 0;
}
