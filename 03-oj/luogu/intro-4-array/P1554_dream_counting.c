/*
 * P1554_dream_counting.c —— 统计 M..N 之间每个数码 0~9 各出现了多少次
 * 来源：洛谷 P1554 [USACO06DEC] 梦中的统计 Dream Counting B
 * 题目：https://www.luogu.com.cn/problem/P1554
 * 日期：2026-11-24
 * 思路：1) 要的是「每个数码各几次」，前提是会「把一个数拆成一位一位」——
 *          这正是 %10 和 /10 的用途。
 *       2) 第一版是「对每个数码 i，把 M..N 全扫一遍」，一共扫 10 遍。
 *       3) 但同一个数被拆 10 遍是浪费：拆一次就能给十个计数器各加一笔，
 *          于是改成「扫一遍 M..N，边拆边 cnt[末位]++」，少一整层循环。
 *          实测 N-M = 5×10^5 时 0.017s → 0.001s，快 17 倍。
 *       4) 能不能不枚举？题目真正给的规模不是 N 多大，而是 N-M ≤ 5×10^5，
 *          区间长度只有五十万，所以逐个枚举完全跑得动。
 * 要点：拆位的固定套路 —— t % 10 取末位、t / 10 去掉末位，while 到 0 停。
 *       cnt[t % 10]++ 相当于 k = t % 10; cnt[k]++，直接拿结果当下标，少一个中间变量。
 *       while (t > 0) 一次都不进的情况（数本身就是 0）不会出现在这里，因为 M ≥ 1。
 * 坑：1) 第一版写的是 while (!n == 0) —— 能跑对，但 `!` 比 `==` 结合得紧，
 *          它其实是 (!n) == 0，等价于 n != 0，碰巧和 !(n == 0) 同义。
 *          换成 while (!n == 1) 就完全是另一回事了（那等价于 n == 0，一次都不进）。
 *          这种「看着像 A、实际是 B、而 B 恰好也对」的写法一律改成 n != 0。
 *       2) j 用 int：N ≤ 2×10^9，而 INT_MAX = 2147483647，刚好装得下；
 *          如果哪天 N 真给到 2147483647，j++ 就会溢出成负数、循环不终止。
 * 建议：1) 输出十个数之间的空格：先打第一个，之后每个「前面」补一个空格，
 *          比「打完再判断是不是最后一个」少一个条件，也不会在行末多一个空格。
 *       2) 拆位可以抽成 count_digit(num, d) 单独一个函数，本题不需要，
 *          但 P1980 数位统计、回文判断、数字反转都会反复用到这一小段。
 */
#include <stdio.h>
int main()
{
    int M, N;
    if (scanf("%d %d", &M, &N) != 2)
        return 1;
    int cnt[10] = {0};
    for (int j = M; j <= N; j++)
    {
        int t = j;
        while (t > 0)
        {
            cnt[t % 10]++;
            t /= 10;
        }
    }
    for (int i = 0; i < 10; i++)
    {
        if (i > 0)
            printf(" ");
        printf("%d", cnt[i]);
    }
    return 0;
}
