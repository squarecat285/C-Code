/*
 * P1427_number_reverse.c —— 小鱼的数字游戏：读到 0 为止，把前面的数倒着念出来
 * 来源：洛谷 P1427 小鱼的数字游戏
 * 题目：https://www.luogu.com.cn/problem/P1427
 * 日期：2026-11-02
 * 思路：1) 事先不知道有几个数，只能一直读，读到 0 就停 —— 典型的 for (;;) + break。
 *       2) 循环变量 i 正好是「现在读到第几个」，顺便当数组下标用。
 *       3) 0 不是答案，所以只在非 0 时才 count++，这样倒着打印时 0 天然被排除，
 *          不用再单独判一次。
 *       4) 题目要求倒序，所以必须先把数存下来 —— 这题数组是绕不过去的。
 * 要点：break 那一刻 count 和 i 是相等的，用一个变量其实就够；分开写更好读。
 *       数据范围 a_i ≤ 2^31 − 1，正好是 int 的上限，用 int 装刚刚好。
 * 坑：没有错。但 scanf 的返回值没检查：万一数据提前结束（EOF），scanf 失败、
 *     s[i] 保持旧值，if (s[i] == 0) 可能永远不成立 → 死循环并越界写栈。
 *     这题靠「保证有且仅有末尾一个 0」才没事，换个题就不保险了。
 * 建议：while (scanf("%d", &x) == 1 && x != 0) s[count++] = x;
 *       一行同时挡掉两种情况：读到 0 停、数据读完也停。
 */
#include <stdio.h>
int main()
{
    int s[105];
    int count = 0;
    int x;
    while (scanf("%d", &x) == 1 && x != 0)
        s[count++] = x;
    for (int i = count - 1; i >= 0; i--)
    {
        printf("%d ", s[i]);
    }
    return 0;
}
