/*
 * P5730_display.c —— 把一串数字按 3×5 点阵字模打印出来，字与字之间隔一列
 * 来源：洛谷 P5730 【深基5.例10】显示屏
 * 题目：https://www.luogu.com.cn/problem/P5730
 * 日期：2026-11-24
 * 思路：1) 输出是 5 行，每行由 n 个 3 字符宽的图案拼成、中间夹一个 '.' ——
 *          所以「按行」是外层循环，遍历每一位数字是内层循环。
 *       2) 每个数字长什么样只有 10 种可能。在循环里用 if/switch 分十支又长又难改，
 *          干脆把十张图直接打表存起来 → font[10][5][4]。
 *       3) 第三维必须是 4 而不是 3：C 的字符串末尾要留一个 '\0'，
 *          否则 printf("%s") 不知道该在哪停，会一路读下去。
 *       4) 分隔的 '.' 换个顺序就不需要判断了：先打第一个数字，
 *          之后每个数字「前面」补一个 '.'，行末自然不会多出一个点。
 * 要点：值域小的时候，「表」比「分支」好 —— font[数字][行] 一次索引就拿到要打的三个字符。
 *       三维数组的读法：第一维选图案，后两维是图案里的坐标。
 *       static 让这张常量表只存在一份、放在只读区，不用每次进函数在栈上重建；
 *       const 让编译器盯着你 —— 手滑写 font[0][0][0] = 'X' 会直接报错。
 * 坑：1) char str[105] 是按 n ≤ 100 再加结尾 '\0' 算出来的，刚好够；
 *          少开一格就是越界写，编译器不会提醒。scanf 也必须限宽成 %104s，
 *          否则输入行一超长就直接写爆 str。
 *       2) 题目保证第二行长度等于 n，但如果 scanf 只读进一半，
 *          后面的 str[i] 读到的是没初始化的字节，打出来的图案会莫名其妙。
 * 建议：1) 这种「字模表」在点阵、七段数码管、图形输出题里会反复出现，值得记成一个套路：
 *          先用小数组把固定形状存好，再按「行优先」把每个字的同一行拼起来。
 *       2) 分隔符和 P1554 输出十个数是同一个技巧 —— 只判断「不是第一个/最后一个」，
 *          不要判断「是第几个」。
 */
#include <stdio.h>
int main()
{
    int n;
    if (scanf("%d", &n) != 1)
        return 1;
    char str[105];
    scanf("%104s", str);
    static const char font[10][5][4] = {
        {"XXX", "X.X", "X.X", "X.X", "XXX"},
        {"..X", "..X", "..X", "..X", "..X"},
        {"XXX", "..X", "XXX", "X..", "XXX"},
        {"XXX", "..X", "XXX", "..X", "XXX"},
        {"X.X", "X.X", "XXX", "..X", "..X"},
        {"XXX", "X..", "XXX", "..X", "XXX"},
        {"XXX", "X..", "XXX", "X.X", "XXX"},
        {"XXX", "..X", "..X", "..X", "..X"},
        {"XXX", "X.X", "XXX", "X.X", "XXX"},
        {"XXX", "X.X", "XXX", "..X", "XXX"},
    };
    for (int row = 0; row < 5; row++)
    {
        for (int i = 0; i < n; i++)
        {
            if (i > 0)
                printf(".");
            int digit = str[i] - '0';
            printf("%s", font[digit][row]);
        }
        printf("\n");
    }
    return 0;
}
