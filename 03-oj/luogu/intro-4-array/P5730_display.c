/*
 * P5730_display.c —— 把一串数字按 3×5 点阵字模打印出来，字与字之间隔一列
 * 来源：洛谷 P5730 【深基5.例10】显示屏
 * 题目：https://www.luogu.com.cn/problem/P5730
 * 日期：2026-11-24
 * 思路：1) 输出是 5 行，每行由 n 个 3 字符宽的图案拼成、中间夹一个 '.' ——
 *          所以「按行」是外层循环，遍历每一位数字是内层循环。
 *       2) 每个数字长什么样只有 10 种可能。在循环里用 if/switch 分十支又长又难改，
 *          干脆把十张图直接打表存起来 → char font[10][5][4]。
 *       3) 第三维必须是 4 而不是 3：C 的字符串末尾要留一个 '\0'，
 *          否则 printf("%s") 不知道该在哪停，会一路读下去。
 *       4) 分隔的 '.' 只在「不是最后一个」时打，否则每行行末都会多一个点。
 * 要点：值域小的时候，「表」比「分支」好 —— font[数字][行] 一次索引就拿到要打的三个字符。
 *       三维数组的读法：第一维选图案，后两维是图案里的坐标。
 * 坑：1) char str[105] 是按 n ≤ 100 再加结尾 '\0' 算出来的，刚好够；
 *          少开一格就是越界写，编译器不会提醒。
 *       2) 题目保证第二行长度等于 n，但如果 scanf 只读进一半，
 *          后面的 str[i] 读到的是没初始化的字节，打出来的图案会莫名其妙。
 * 建议：1) scanf("%s", str) 不限宽，改成 scanf("%104s", str) 更稳，
 *          万一输入行超长也不会写爆 str。
 *       2) font 是常量表，加 static const 放到只读区，省掉每次进 main 在栈上重建 200 字节。
 *       3) 分隔符可以换个顺序：先打第一个数字，之后每个数字「前面」补一个 '.'，
 *          这样就不需要 i < n - 1 这个判断了。
 *       4) printf("\n"); 现在跟在上一个 for 的 } 后面写成 }printf("\n");，
 *          单独一行更符合本仓库的排版习惯。
 */
#include <stdio.h>
int main()
{
    int n;
    if (scanf("%d", &n) != 1)
        return 1;
    char str[105];
    scanf("%s", str);
    char font[10][5][4] = {
        {"XXX", "X.X", "X.X", "X.X", "XXX"},
        {"..X", "..X", "..X", "..X", "..X"},
        {"XXX", "..X", "XXX", "X..", "XXX"},
        {"XXX", "..X", "XXX", "..X", "XXX"},
        {"X.X", "X.X", "XXX", "..X", "..X"},
        {"XXX", "X..", "XXX", "..X", "XXX"},
        {"XXX", "X..", "XXX", "X.X", "XXX"},
        {"XXX", "..X", "..X", "..X", "..X"},
        {"XXX", "X.X", "XXX", "X.X", "XXX"},
        {"XXX", "X.X", "XXX", "..X", "XXX"},
    };
    for (int row = 0; row < 5; row++)
    {
        for (int i = 0; i < n; i++)
        {
            int digit = str[i] - '0';
            printf("%s", font[digit][row]);
            if (i < n - 1)
            {
                printf(".");
            }
        }printf("\n");
    }
    return 0;
}
