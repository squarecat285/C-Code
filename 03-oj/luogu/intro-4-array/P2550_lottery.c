/*
 * P2550_lottery.c —— [AHOI2001] 彩票摇奖
 * 来源：洛谷题单【入门4】数组
 * 题目：https://www.luogu.com.cn/problem/P2550
 * 日期：2026-11-14
 * 思路：1) 每张票只关心「中了几个号」，不关心是哪几个 —— 先把统计口径定下来
 *       2) 「中几个」= 这张票的 7 个号里有几个出现在中奖名单里，需要一个「在不在名单」的快速判断
 *       3) 号码范围只有 1~33，值域这么小就不该挨个比 —— 开 win[34] 当标记表，查一次就够
 *       4) 结果要按「中几个」分堆，而命中数本身就是 0~7 的整数，直接当数组下标用：
 *          grade[命中数]++，天然有序，连排序都省了
 *       5) 题目要按「中 7 个 → 中 1 个」输出，所以倒着打 grade[7..1]；
 *          下标要能取到 7，数组就得开 8 格
 * 要点：值域小 → 数组当查找表。中奖名单存成标记表后，每张票只需要 7 次查表，
 *       而不是 7 × 7 = 49 次比较（本机微基准：同一个统计内核 0.0410s vs 0.1580s，约 3.85 倍）
 *       票读一张、算一张、扔掉，不用整批存下来 —— 省掉 28 KB 栈，也顺带免了 n 的边界问题
 * 坑：1) 第一版开的是 int a[7]，但「中了几个号」最大是 7，a[7] 已经越界一格
 *     2) 输出又写成 for (i = 6; i >= 0; i--)，打的是 a[6]..a[0] =「中 6 个…中 0 个」，
 *        整排往左错了一位：特等奖没打出来，末尾反而凭空多一个「中 0 个」
 *     3) 这两个错其实是同一个：把「7 个奖项」和「命中数 0~7 共 8 种」混成一个 7
 *        65 组用例错 64 组，但「各档各一张」因为上下对称（都是 1）碰巧全对
 * 建议：数组长度 = 最大值 + 1；输出范围从「题目要输出几个数」推，不要从「数组有几个格子」推。
 *       测样例时要专挑不对称的（只中特等奖、只中 1 个、一个都没中），对称用例测不出错位。
 *       这题和自己记的一句话一样：可以找一个第三者作为桥梁来沟通，这里的桥梁就是 win[34]。
 *       另外 win[v] 本身就是 0/1，直接写 if (win[v]) 就是「在不在名单」的判断，
 *       不必再写 == 1 —— 用值和 0 比较（if (x) / if (!x)）是 C 的习惯写法。
 */
#include <stdio.h>
int main()
{
    int n;
    if (scanf("%d", &n) != 1)
        return 1;

    int win[34] = {0};

    for (int i = 0; i < 7; i++)
    {
        int v;
        if (scanf("%d", &v) != 1)
            return 1;
        win[v] = 1;
    }

    int grade[8] = {0};
    for (int i = 0; i < n; i++)
    {
        int hits = 0;
        for (int j = 0; j < 7; j++)
        {
            int v;
            if (scanf("%d", &v) != 1)
                return 1;
            if (win[v])
                hits++;
        }
        grade[hits]++;
    }
    for (int i = 7; i >= 1; i--)
        printf("%d%c", grade[i], i == 1 ? '\n' : ' ');
    return 0;
}

