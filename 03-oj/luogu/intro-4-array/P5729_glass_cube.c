/*
 * P5729_glass_cube.c —— 工艺品制作：w×x×h 的实心立方体被激光挖掉 q 个长方体，还剩几格
 * 来源：洛谷 P5729 【深基5.例7】工艺品制作
 * 题目：https://www.luogu.com.cn/problem/P5729
 * 日期：2026-11-04
 * 思路：1) 每一格 1×1×1 的小方块只有「还在 / 被蒸发」两种状态，一个数组就够当开关表。
 *       2) 坐标本来就是 1 开始、连续到 w/x/h，天生就是数组下标 —— 直接拿 (i,j,k) 索引，
 *          不用做任何换算。
 *       3) 每次切割要蒸发的是一个长方体，那就是三重循环把
 *          [x1..x2] × [y1..y2] × [z1..z2] 全标成 1。
 *       4) 最后三重循环把还在的（值为 0 的）数一遍。
 *       5) 同一格被切第二次、第三次都无所谓 —— 标记成 1 再标一次还是 1。
 *          这正是标记数组比「体积相减」强的地方：天然去重，不用判重叠。
 * 要点：三维数组 cube[i][j][k] 里 i 是最外层。合法下标是 0 ~ 长度-1，
 *       坐标最大到 20 且从 1 开始，所以每一维至少要 21 格，开 25 留余量。
 * 坑：第一版写 int cube[20][20][20]，合法下标只到 19，坐标 20 就已经出界了
 *     （20*20*20*4 = 32000 字节，而 cube[20][0][0] 的偏移正好是 32000）。
 *     w = x = h = 20、只切 (20,20,20) 这一格时，同一个输入连跑 8 次：
 *     5 次直接段错误 rc = 3221225477 (0xC0000005)，3 次输出 7970（应 7999）。
 *     159 组随机+边界错 9 组；只把数组改成 [25][25][25] 就 0 组错。
 *     gcc 零警告 —— 越界这种事编译器从来不管。
 * 建议：数据再大就该换三维差分：每次切割只在 8 个角上 +1 / -1，
 *       最后跑一遍三维前缀和得到每格被切的次数，复杂度从 O(q·体积) 降到 O(q + 体积)。
 *       现在 q ≤ 100、体积 ≤ 8000，最坏 8×10^5 次赋值，跑得飞快，不必上差分。
 */
#include <stdio.h>
int main()
{
    int W, X, H;
    if (scanf("%d %d %d", &W, &X, &H) != 3)
    {
        return 1;
    }
    int cube[25][25][25] = {0};
    int q;
    if (scanf("%d", &q) != 1)
    {
        return 1;
    }
    for (int t = 0; t < q; t++)
    {
        int x1, y1, z1, x2, y2, z2;
        if (scanf("%d %d %d %d %d %d", &x1, &y1, &z1, &x2, &y2, &z2) != 6)
        {
            return 1;
        }
        for (int i = x1; i <= x2; i++)
        {
            for (int j = y1; j <= y2; j++)
            {
                for (int k = z1; k <= z2; k++)
                {
                    cube[i][j][k] = 1;
                }
            }
        }
    }
    int count = 0;
    for (int i = 1; i <= W; i++)
    {
        for (int j = 1; j <= X; j++)
        {
            for (int k = 1; k <= H; k++)
            {
                if (cube[i][j][k] == 0)
                {
                    count++;
                }
            }
        }
    }
    printf("%d", count);
    return 0;
}
