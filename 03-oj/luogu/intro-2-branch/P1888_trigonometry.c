/*
 * P1888_trigonometry.c —— 三角函数：给一组勾股数，输出较小锐角正弦值的最简分数
 * 来源：洛谷 P1888 三角函数
 * 题目：https://www.luogu.com.cn/problem/P1888
 * 日期：2026-10-22
 * 思路：1) 题目要「较小锐角的正弦」，而较小锐角对着的是最短那条直角边，
 *          所以正弦 = 对边 / 斜边 = 最短边 / 最长边。
 *       2) 输入乱序，得先把最长边（斜边）和最短边找出来 —— 两轮三元比较就够。
 *       3) 直接输出 min/max 不合题意（6 8 10 会输出 6/10），要化成最简分数：
 *          分子分母同除它们的最大公约数。
 *       4) 最大公约数用辗转相除：gcd(a,b) = gcd(b, a%b)，b 归零时 a 就是答案，
 *          比「从 1 枚举到 min」快得多。
 * 要点：勾股数 a、b、c 互不相等且无大小顺序，但直角三角形的斜边一定是最长那条，
 *       所以先分别找出 max（斜边）和 min（最短的直角边）。
 *       较小锐角对着最短的直角边，正弦 = 对边 / 斜边 = min / max，
 *       约分就是分子分母同除以 gcd(min, max)。
 *       数据到 10^9，int 装得下（int 上限约 2.1 × 10^9），不用开 long long。
 *
 * 辗转相除法（欧几里得算法）求最大公约数：
 *
 *   原理：gcd(a, b) = gcd(b, a % b)。两个最大公约数相等，所以可以一直化简下去。
 *   理由：设 a = q * b + r，那么 r = a - q * b。
 *       能同时整除 a、b 的数，一定也能整除 r（它俩的线性组合）；
 *       反过来，能同时整除 b、r 的数，一定也能整除 a = q * b + r。
 *       所以「a 和 b 的公约数」和「b 和 r 的公约数」是同一批数，最大公约数自然相同。
 *
 *   终止：b == 0 时 gcd(a, 0) = a，此时 a 就是答案。
 *
 *   手算 gcd(12, 8)：
 *       12 % 8 = 4   → 变成 gcd(8, 4)
 *        8 % 4 = 0   → 变成 gcd(4, 0)
 *       b 已经是 0，返回 a = 4
 *
 *   代码里那个 temp 是必须的，顺序不能省：
 *       int temp = b;   // 先把旧的 b 存下来
 *       b = a % b;      // 新的 b 是余数（这行已经覆盖掉 b，所以上面必须先存）
 *       a = temp;       // 新的 a 是旧的 b
 *   写成 a = b; b = a % b; 就错了 —— 算余数时用的已经是新的 a。
 *
 *   复杂度：每一轮余数至少减半，最多 log(min(a, b)) 轮。
 *   10^9 以内也就几十轮，比「从 1 枚举到 min」快得多。
 *
 * 坑：方向别搞反——题目要的是较小锐角的正弦，是最短边 / 斜边；
 *     忘了约分时 6 8 10 会输出 6/10，正确答案是 3/5。
 *     另外斜边永远是最大那条，不能凭输入顺序把第三个当斜边。
 */
#include <stdio.h>
int gcd(int a, int b)
{
    while (b != 0)
    {
        int temp = b;
        b = a % b;
        a = temp;
    }
    return a;
}
int main()
{
    int a, b, c;
    scanf("%d %d %d", &a, &b, &c);
    int max = (a > b) ? a : b;
    max = (max > c) ? max : c;
    int min = (a < b) ? a : b;
    min = (min < c) ? min : c;
    int g = gcd(max, min);
    printf("%d/%d", min / g, max / g);
    return 0;
}
