/*
 * P1055_isbn.c —— ISBN 号码：校验识别码，错了就输出改正后的完整号码
 * 来源：洛谷 P1055 [NOIP 2008 普及组] ISBN 号码
 * 题目：https://www.luogu.com.cn/problem/P1055
 * 日期：2026-10-23
 * 思路：1) 号码是 13 个字符的字符串，不是数 —— 里面夹着 '-'，还可能以 'X' 结尾。
 *          当整数读，'-' 和 'X' 都没法表示，所以只能开 char 数组。
 *       2) 真正参与计算的是 9 个数字，位置固定：下标 1、5、11 是横线，跳过；
 *          剩下的下标 0、2、3、4、6、7、8、9、10 依次乘 1~9。
 *          位数和权重都写死，比写循环跳过 '-' 更不容易错位。
 *       3) 求和后 % 11 得识别码，余数 10 时识别码要写成大写 'X'。
 *       4) 校验时把末位和余数比：余数 10 跟 'X' 比，否则跟 s[12]-'0' 比。
 *          对得上输出 Right，对不上就把前 12 个字符原样重打、再补上正确的识别码。
 * 要点：1) 前 9 位数字分别乘 1~9 再求和，和 % 11 的余数就是识别码；
 *          余数为 10 时识别码写成大写 X。
 *       2) 号码里夹着三个 '-'，13 个字符中下标 1、5、11 是横线，
 *          真正参与计算的数字在下标 0、2、3、4、6、7、8、9、10。
 *          直接按下标写死比用循环跳过 '-' 省事，也不会错位。
 *       3) 校验时把余数当数字比，X 单独处理：
 *          余数 10 且末位是 'X' → Right；
 *          余数等于 s[12] - '0' → Right；
 *          其余情况都要把正确号码整个重打一遍。
 *          （不用再判「余数不是 10」：s[12] - '0' 最大就是 9，
 *            余数 10 永远等不上它，所以那个条件本来就是多余的。）
 *       4) 重打时前 12 个字符原样输出（含最后那个 '-'），再补上正确识别码。
 *
 * 坑：char s[13] 装不下 13 个字符！scanf("%s") 读完还会补一个 '\0' 结尾，
 *     那个字节会写到 s[13]，越界 1 字节。必须开 char s[14]。
 *     gcc 对这种越界不会报警告，运行时也常常「看着是对的」，
 *     但它踩的是栈上相邻的变量——属于最难查的一类 bug。
 *     s[14] 是「这个数组能装 14 个字符」，s[12] 是「第 13 个字符」：
 *     下标从 0 开始数，差一是常态，读到 s[13] 就是数组外面了。
 *     （和 P4414 里 char s[3] 装三个字母是同一个坑：
 *       数组长度 = 最多字符数 + 1。）
 */
#include <stdio.h>
int main()
{
    char s[14]; /* 13 个字符 + 结尾的 '\0' = 14 */
    scanf("%s", s);
    int sum = (s[0] - '0') * 1 + (s[2] - '0') * 2 + (s[3] - '0') * 3 + (s[4] - '0') * 4 + (s[6] - '0') * 5 + (s[7] - '0') * 6 + (s[8] - '0') * 7 + (s[9] - '0') * 8 + (s[10] - '0') * 9;
    int mod11 = sum % 11;
    if (mod11 == 10 && s[12] == 'X')
    {
        printf("Right");
    }
    else if (mod11 == s[12] - '0')
    {
        printf("Right");
    }
    else
    {
        for (int i = 0; i < 12; i++)
        {
            printf("%c", s[i]);
        }
        if (mod11 == 10)
        {
            printf("X");
        }
        else
        {
            printf("%d", mod11);
        }
    }
    return 0;
}
