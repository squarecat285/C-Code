/*
 * P5715_number_sort.c —— 三位数排序：读入三个整数，从小到大输出
 * 来源：洛谷 P5715 【深基3.例8】三位数排序
 * 题目：https://www.luogu.com.cn/problem/P5715
 * 日期：2026-10-21
 * 思路：1) 三个数排序用不着冒泡，三次比较就够 —— 这叫排序网络。
 *       2) 把目标拆成两个小目标：先让第一个是三者最小，再让后两个有序。
 *       3) 先比 a、b，再比 a、c —— 两轮下来 a 一定最小；
 *          最后一次比 b、c，后两个也就正好了。
 *       4) 每一步都是同一个动作「前面的比后面大就交换」，
 *          所以三段代码长得一模一样，只是变量不同。
 * 要点：三个 if 交换就是一张排序网络，三次比较就够，不用冒泡：
 *       先拿 a 跟 b、c 比，把最小的换到 a；
 *       再比 b 和 c，剩下的两个自然就排好了。
 */
#include <stdio.h>
int main()
{
    int a, b, c;
    scanf("%d %d %d", &a, &b, &c);
    if (a > b)
    {
        int t = a;
        a = b, b = t;
    }
    if (a > c)
    {
        int t = a;
        a = c, c = t;
    }
    if (b > c)
    {
        int t = b;
        b = c, c = t;
    }
    printf("%d %d %d", a, b, c);
    return 0;
}
