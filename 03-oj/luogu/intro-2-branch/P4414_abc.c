/*
 * P4414_abc.c —— ABC：三个数按第二行给出的字母顺序重排后输出
 * 来源：洛谷 P4414 [COCI 2006/2007 #2] ABC
 * 题目：https://www.luogu.com.cn/problem/P4414
 * 日期：2026-10-23
 * 要点：1) 先用三行 if 交换把三个数从小到大排好——排完 n[0] 就是 A（最小）、
 *          n[1] 是 B、n[2] 是 C（最大）。三个数排序只需要 3 次比较，
 *          顺序是「先让 n[0] 最小，再让 n[1] <= n[2]」。
 *       2) 字母不用排序，只要查表：s[i] - 'A' 把 'A' 变成 0、'B' 变 1、'C' 变 2，
 *          正好当数组下标，n[s[i] - 'A'] 就是那个字母代表的值。
 *       3) 第二行三个字母之间没有空格，直接当字符串读：scanf("%s", s)。
 *          C 的字符串必须以 '\0' 结尾，3 个字母要开 char s[4]（多出那格给 '\0'）。
 *       4) 输出末尾不能多空格，所以空格跟着后面的数字打，用 if (i < 2) 挡住最后一个。
 *
 * 坑：1) scanf("%d", n[i]) 少了 &，scanf 会把「n[i] 里的值」当地址去写，
 *          运行时直接段错误（退出码 139）。gcc 其实报了
 *          format '%d' expects argument of type 'int *', but argument 2 has type 'int'。
 *          数组元素的地址是 &n[i]，也可以写 n + i。
 *       2) 一开始把「排数字」和「排字母」写成两段一模一样的 if 交换，
 *          字母那段的交换体里还写着 a、b、c。这套写法只在 6 种字母顺序里的 5 种
 *          碰巧对得上，唯独 BCA 会错——洛谷上就是 9/10 AC、挂在第 9 个点。
 *          本质错误：字母不需要排序，需要的是「按字母去取值」。
 *       3) 读字母时写成 scanf("%c%c%c", ...) 没加前导空格：
 *          上一行 %d 吃完数字后，行尾那个换行还留在缓冲区，而 %c 不跳过空白，
 *          于是第一个字母拿到的其实是 '\n'，三个字母整体错位，最后一个根本读不进来。
 */
#include <stdio.h>
int main()
{
    int n[3];
    for (int i = 0; i < 3; i++)
    {
        scanf("%d", &n[i]);
    }
    if (n[0] > n[1])
    {
        int t = n[0];
        n[0] = n[1];
        n[1] = t;
    }
    if (n[0] > n[2])
    {
        int t = n[0];
        n[0] = n[2];
        n[2] = t;
    }
    if (n[1] > n[2])
    {
        int t = n[1];
        n[1] = n[2];
        n[2] = t;
    }
    char s[4];
    scanf("%s", s);
    for (int i = 0; i < 3; i++)
    {
        printf("%d", n[s[i] - 'A']);
        if (i < 2)
        {
            printf(" ");
        }
    }
    return 0;
}

