/*
 * P1424_fish_journey.c —— 小鱼的航程（改进版）：从周 x 起过 n 天，工作日每天 250 公里，周末休息
 * 来源：洛谷 P1424 小鱼的航程（改进版）
 * 题目：https://www.luogu.com.cn/problem/P1424
 * 日期：2026-10-22
 * 思路：1) 第一反应是按周算：整周 5 个工作日 × 250，再补零头。
 *          但零头那一段最容易出错 —— 补「本周剩余天数」时，n 可能根本不够那么多天。
 *       2) 退一步：n ≤ 10^6，一天一次加法完全跑得动，那就逐天模拟。
 *       3) 从周 x 起，第 i 天是周几？(x - 1 + i) % 7 + 1：先挪到 0 基（周日当 0），
 *          取模绕圈，再转回 1~7。
 *       4) 只要这天 ≤ 5 就是工作日，加 250；循环跑 n 次，
 *          「n 到了就停」直接写进循环条件，不会多算。
 * 要点：逐天模拟：第 i 天是 (x - 1 + i) % 7 + 1 号（1~7），
 *       只要 ≤ 5 就算一个工作日、加 250 公里。
 *       (x - 1 + i) % 7 把「从周 x 起往后推 i 天」换算成 0~6，
 *       再 + 1 转回周几，这是「循环里数星期」最省事的写法。
 *       题目 n ≤ 10^6，一天一次加法，一百万次也是一瞬间，不需要刻意优化。
 * 坑：原来写的是「先补完本周剩下的日子，再用 n / 7 乘整周，最后补零头」，
 *     开头那个 for (int i = x; i <= 7; i++) 没有用 n 限制，
 *     它总是把本周剩下的工作日全部加完，哪怕 n 根本不够用掉这些天。
 *     x=1 n=1 应该是 250（只游周一这一天的），当时给的是 1250（周一到周五全算了）。
 *     1≤x≤7、1≤n≤200 共 1400 组里错 10 组，全是「n 比本周剩下的天数还短」的情况；
 *     n ≥ 8 之后全对，所以官方样例和 n 很大的数据都测不出来。
 *     换成逐天模拟后，175 组边界值复验 0 错。
 * 建议：如果以后 n 大得多（比如 10^18，逐天模拟跑不动了），再把「整周」提出来：
 *       weeks = n / 7 直接乘 5 * 250，剩下 n % 7 天用逐天判断补上。
 *       这样既快又不会踩「n 不够本周剩余天数」那个洞。
 */
#include <stdio.h>
int main()
{
    int x, n, distance = 0;
    scanf("%d %d", &x, &n);
    for (int i = 0; i < n; i++)
    {
        int w = (x - 1 + i) % 7 + 1;

        if (w <= 5)
            distance += 250;
    }
    printf("%d", distance);
    return 0;
}
