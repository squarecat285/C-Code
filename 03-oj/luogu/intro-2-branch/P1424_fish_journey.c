/*
 * P1424_fish_journey.c —— 小鱼的航程（改进版）：从周 x 起过 n 天，工作日每天 250 公里，周末休息
 * 来源：洛谷 P1424 小鱼的航程（改进版）
 * 题目：https://www.luogu.com.cn/problem/P1424
 * 日期：2026-10-22
 * 要点：思路是「先补完本周剩下的日子，再用 n / 7 乘整周，最后补零头」。
 *       每周固定 5 个工作日，所以整周部分一定是 weeks * 5 * 250，不用逐天加。
 *       n = n - (7 - x) - 1 这里借的是「本周还剩几天」，
 *       减 1 是因为当周那几天已经在第一个循环里算过了。
 * 坑：开头那个 for (int i = x; i <= 7; i++) 没有用 n 限制，
 *     它总是把本周剩下的工作日全部加完，哪怕 n 根本不够用掉这些天。
 *     x=1 n=1 应该是 250（只游周一这一天的），程序给的是 1250（周一到周五全算了）。
 *     1≤x≤7、1≤n≤200 共 1400 组里错 10 组，全是「n 比本周剩下的天数还短」的情况；
 *     n ≥ 8 之后全对，所以官方样例和 n 很大的数据都测不出来。
 * 建议：这题 n ≤ 10^6，一天一天数完全跑得动（一百万次加法是一瞬间的事），
 *       不用做「借本周剩余天数」这种推导，一段循环就够，也不会漏边界：
 *
 *           int total = 0;
 *           for (int i = 0; i < n; i++)
 *           {
 *               int w = (x - 1 + i) % 7 + 1;   // 第 i 天是周几，1~7
 *               if (w <= 5) total += 250;
 *           }
 *
 *       如果还想保留算式写法，把「整周」和「零头」分开就行：
 *       weeks = n / 7 直接乘 5 * 250，剩下 n % 7 天再用一段循环判断。
 *       这样根本不需要「先补完本周剩余天数」这一步，n 再小也不会出错。
 */
#include <stdio.h>
int main()
{
    int x, n, distance=0;
    scanf("%d %d", &x, &n);
    for (int i = x; i <= 7; i++)
    {
        if (i <= 5)
            distance += 250;
        else
            break;
    }
    n = n - (7 - x) - 1;
    if (n <= 0)
    {
        printf("%d", distance);

        return 0;
    }
    int weeks = n / 7;
    distance += 250 * 5 * weeks;
    int extra = n % 7;
    for (int i = 1; i <= extra; i++)
    {
        if (i <= 5)
            distance += 250;
        else
            break;
    }
    printf("%d", distance);
    return 0;
}
