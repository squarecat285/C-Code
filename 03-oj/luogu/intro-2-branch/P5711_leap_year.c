/*
 * P5711_leap_year.c —— 闰年判断：是闰年输出 1，否则输出 0
 * 来源：洛谷 P5711 【深基3.例3】闰年判断
 * 题目：https://www.luogu.com.cn/problem/P5711
 * 结果：⬜ 待提交（本地 1582~2020 全对）
 * 日期：2026-10-20
 * 要点：闰年 = （能被 4 整除 且 不能被 100 整除） 或 （能被 400 整除）。
 *       后半段管的是 1600、2000 这种整百年，前两百年一票否决。
 * 坑：1) 后半段写成了 a % 100 == 0 —— a 正是这一行要赋值的变量，
 *       此刻它还是 0，0 % 100 == 0 恒为真，于是不管哪一年都输出 1
 *       （1582~2020 共 439 年里错了 332 个）。
 *    2) 就算把 a 改成 n，n % 100 == 0 也不对：1900 是整百年但不是 400 的倍数，
 *       按定义是平年，必须写 n % 400 == 0。
 *       数据范围 1582 <= n <= 2020，1900 正好在里面，专打「% 100 就够了」的写法。
 */
#include <stdio.h>
int main()
{
    int n;
    scanf("%d", &n);
    int a = 0;
    a = (n % 4 == 0 && n % 100 != 0) || (n % 400 == 0);
    printf("%d", a);
    return 0;
}
