/*
 * P5710_number_properties.c —— 数的性质：判断 x 是否同时满足「是偶数」「大于 4 且不大于 12」
 * 来源：洛谷 P5710 【深基3.例2】数的性质
 * 题目：https://www.luogu.com.cn/problem/P5710
 * 结果：⬜ 未做
 * 日期：2026-10-19
 * 要点：两个性质 A、B 一共只有四种组合，四个输出正好一一对应：
 *       都满足 = A && B，至少一个 = A || B，恰好一个 = A != B，一个都没有 = !(A || B)。
 *       先把 A、B 各存成变量，四个答案就都是同一行能看懂的东西。
 * 坑：1) 「一个都没有」写成了 !(A && B) —— 那是「不都满足」，
 *       两者只在「恰好满足一个」时不同，0~1000 里错了 501 个，一半。
 *    2) 改的时候又写成 !(A && (a > 4 || a <= 12))：a > 4 || a <= 12 恒为真，
 *       整个式子退化成 !A。德摩根要「且和或同时取反」，不能只动一个运算符。
 *       最稳的写法是复用算好的变量：neither = !any。
 */
#include <stdio.h>

int main()
{
    int x;
    scanf("%d", &x);

    int p1 = (x % 2 == 0);            /* 性质 1：偶数 */
    int p2 = (x > 4 && x <= 12);      /* 性质 2：大于 4 且不大于 12 */

    int both = (p1 && p2);            /* 小A：两个都满足 */
    int any = (p1 || p2);             /* Uim：至少满足一个 */
    int exactly_one = (p1 != p2);     /* 小B：恰好满足一个 */
    int neither = !any;               /* 正妹：一个都不满足 */

    printf("%d %d %d %d", both, any, exactly_one, neither);
    return 0;
}
