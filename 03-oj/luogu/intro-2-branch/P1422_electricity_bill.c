/*
 * P1422_electricity_bill.c —— 小玉家的电费：阶梯电价，分段计价
 * 来源：洛谷 P1422 小玉家的电费
 * 题目：https://www.luogu.com.cn/problem/P1422
 * 日期：2026-10-22
 * 要点：阶梯电价是「分段累加」，不是「拿总量套一个价」：
 *       前 150 度每度 0.4463，第 151~400 度每度 0.4663，第 401 度起每度 0.5663。
 *       所以第二段必须写 150 * 0.4463 + (n - 150) * 0.4663，
 *       不能写 n * 0.4663——那样前 150 度也按贵价算了。
 * 坑：printf("%.1f") 本身就四舍五入，不要自己再取整一次。
 *     原来多写了一行 cost = (int)(cost * 10) / 10.0; 以为在四舍五入，
 *     其实 (int) 是直接砍掉小数 → 第二位小数 ≥ 5 的全部少 0.1。
 *     1~10000 共错 4995 组（49.95%），从 n=2 就错（0.8926 打成 0.8，应 0.9）。
 *     样例 267 恰好看不出来：121.5021 砍掉和进位都是 121.5。
 * 也别改成 (int)(cost * 10 + 0.5) / 10.0：500 / 3500 / 4500 / 7500 这四个值
 *     精确电费恰好是 x.x5（240.1500、1939.0500、2505.3500、4204.2500），
 *     但 double 里 240.15 存的是 240.14999…，printf 会给 240.1，
 *     手写 +0.5 会给 240.2，两者不同。跟住 printf 就好。
 */
#include <stdio.h>
int main()
{
    double consumption, cost;
    scanf("%lf", &consumption);
    if (consumption <= 150)
    {
        cost = consumption * 0.4463;
    }
    else if (consumption <= 400)
    {
        cost = 150 * 0.4463 + (consumption - 150) * 0.4663;
    }
    else
    {
        cost = 150 * 0.4463 + 250 * 0.4663 + (consumption - 400) * 0.5663;
    }
    printf("%.1f", cost);
    return 0;
}
