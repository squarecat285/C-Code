/*
 * P1720_fibonacci_money.c —— 月落乌啼算钱：求第 n 个斐波那契数，保留两位小数
 * 来源：洛谷 P1720 月落乌啼算钱（斐波那契数列）
 * 题目：https://www.luogu.com.cn/problem/P1720
 * 日期：2026-10-29
 * 思路：1) 题面给的是 Binet 公式，用 double 算 √5 的幂看着最直接 ——
 *          但 n 到 48 时 (1.618…)^48 已经很大，浮点误差会被放大，
 *          %.2f 有可能差 0.01。
 *       2) 换个角度认这个公式：它算出来的正是斐波那契数列 0, 1, 1, 2, 3, 5, 8, …
 *       3) 既然是递推数列，就直接递推：F(i) = F(i−1) + F(i−2)，
 *          全程整数，一位都不差。
 *       4) 递推要「记住前两项」，用数组一路存下来最直接；n 只到 48，
 *          F(48) = 4807526976，long long 装得下（int 装不下）。
 * 要点：n = 0 时 F(0) = 0，要单独处理 —— 数组是从 F(1) 开始存的（s[0] = 1）。
 *       输出两位小数用 %.2f，把整数转成 double 再打 —— 这就是末尾那句注释
 *       「(类型)用来强制转型」的意思：不加 (double) 直接 %f 打 long long 是未定义行为。
 * 坑：long long s[48] 的下标只能到 47。n = 48 时循环正好写到 s[47]，卡在边界上 ——
 *     再差一格就越界。开数组时习惯多开两三格，比精准计算安全得多。
 */
#include <stdio.h>
int main()
{
    int n;
    long long s[48] = {1, 1};
    scanf("%d", &n);
    for (int i = 2; i < n; i++)
    {
        s[i] = s[i - 2] + s[i - 1];
    }
    if (n == 0)
        printf("0.00");
    else
        printf("%.2f", (double)s[n - 1]);
    return 0;
}
