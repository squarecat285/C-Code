/*
 * P2669_gold_coin.c —— 金币：第 n 天发 n 枚，连续发 k 天，求一共多少枚
 * 来源：洛谷 P2669 [NOIP 2015 普及组] 金币
 * 题目：https://www.luogu.com.cn/problem/P2669
 * 日期：2026-10-26
 * 思路：1) 先别急着找公式。把题目给的串写出来：「1, 2 2, 3 3 3, 4 4 4 4, …」
 *          —— 它是按「组」长大的：第 1 组 1 天，第 2 组 2 天，第 n 组 n 天。
 *       2) 关键观察：第几组，就等于这一组每天发几枚。所以外层循环变量 i
 *          一份当两份用：既数「现在是第几组」，也代表「这一天发 i 枚」。
 *       3) 组是变长的，进了第 i 组还要在内层数「这一组里的第几天」——
 *          j 从 1 数到 i。
 *       4) 天数不一定正好停在组边界上，第 i 组可能只发到一半 k 就用完了。
 *          所以每发一天都得看 count 有没有到 k，到了立刻 break。
 *       5) break 只跳出离它最近的那一层。内层跳出来之后，
 *          外层还得再判一次、再 break 一次。
 * 要点：k ≤ 10^4，走到第 141 组左右就够（141 × 142 / 2 = 10011），
 *       外层加内层总共几千次加法，用不着 O(1) 的公式。
 * 坑：外层少了那个 if (count == k) break; 就完了 —— 内层停了，外层没有终止条件
 *     （写的是 for (int i = 1;; i++)），会一直往上跑，sum 溢出成负数。
 *     要跳出两层循环，就得写两个 break。
 */
#include <stdio.h>
int main()
{
    int k;
    int sum = 0;
    int count = 0;
    scanf("%d", &k);
    for (int i = 1;; i++)
    {
        for (int j = 1; j <= i; j++)
        {
            sum += i;
            count++;
            if (count == k)
                break;
        }

        if (count == k)
            break;
    }
    printf("%d", sum);
    return 0;
}
