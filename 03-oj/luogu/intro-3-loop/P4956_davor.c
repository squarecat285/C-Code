/*
 * P4956_davor.c —— Davor 存钱：52 周每周多存 K 元，求初始值 X 和增量 K
 * 来源：洛谷 P4956 [COCI 2017/2018 #6] Davor
 * 题目：https://www.luogu.com.cn/problem/P4956
 * 日期：2026-11-01
 * 思路：1) 先看一周：X, X+K, X+2K, …, X+6K 加起来是 7X + 21K，也就是 7(X + 3K)。
 *       2) 再看 52 周：52 × 7(X + 3K) = 364(X + 3K)。所以 N 里能整除出一个
 *          「X + 3K」，即 n = N / 364 —— 这一步把两个未知数压成了一个。
 *       3) 题目要 X 最大、K 最小。而 X = n - 3K，K 越小 X 越大，这两个要求
 *          本来就是同一件事，所以只需要从 K = 1 往上找第一个让 X ≤ 100 的 K。
 *       4) 循环里先赋值再 k++，退出时 k 已经多加了 1，所以输出 k - 1。
 * 要点：52 × 7 = 364 是整条等式里唯一需要的常数，不用真去模拟 52 个星期。
 *       「两个要求其实等价」这种化简，是这类题最省事的地方——先写等式，再挑好求的那个。
 * 坑：没有错，一次就对了。N 保证有解，所以 N 一定是 364 的倍数，整数除法不丢精度；
 *     1456 ≤ N ≤ 145600 之间恰好有 397 个这样的 N，全部核对过，0 组不一致。
 * 建议：这个哨兵写法（x 初值 101、靠 while (x > 100) 退出）能用但绕。
 *       其实可以一步算出来：X ≤ 100 要求 n - 3K ≤ 100，即 K ≥ (n - 100) / 3，
 *       所以 K = max(1, ceil((n - 100) / 3))，循环整个可以省掉。留着当练习对照。
 */
#include <stdio.h>
int main()
{
    int N;
    scanf("%d", &N);
    int n = N / (52 * 7);
    int x=101, k = 1;
    while (x > 100)
    {
        x = n - 3 * k;
        k++;
    }
    printf("%d\n%d", x, k-1);
    return 0;
}
