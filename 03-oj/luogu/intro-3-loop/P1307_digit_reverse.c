/*
 * P1307_digit_reverse.c —— 数字反转：把一个整数倒过来写，去掉前导零
 * 来源：洛谷 P1307 [NOIP 2011 普及组] 数字反转
 * 题目：https://www.luogu.com.cn/problem/P1307
 * 日期：2026-10-29
 * 思路：1) 「倒过来写」逐位看就是：从个位开始一位一位挤出来，
 *          每挤出一位就接在新数的末尾 —— t = n % 10; m = m * 10 + t。
 *       2) 负号跟数字本身无关，别在循环里纠缠：先打一个 '-'，把 n 取绝对值，
 *          剩下按正数处理。
 *       3) 前导零不用特意去：m 是整数，120 反转时最后那个 0 进了 m * 10
 *          也不会留下痕迹，自然就是 21。
 * 要点：N 到 10^9，反转后最多九位（999999999），int 其实装得下；
 *       用 long long 是更稳的写法，省得算边界。
 * 坑：输入 0 时 while (n > 0) 一次都不执行，m 还是 0，正好输出 0 —— 这是对的，
 *     别为了「至少转一次」改成 do-while。
 *     负数分支里别忘 n = -n，不然循环条件直接不成立，最后只剩一个 '-'。
 */
#include <stdio.h>
int main()
{
    long long n;
    long long m = 0;

    scanf("%lld", &n);
    if (n < 0)
    {
        printf("-");
        n = -n;
    }
    while (n > 0)
    {
        int t;
        t = n % 10;
        n = n / 10;
        m = m * 10 + t;
    }
    printf("%lld", m);
    return 0;
}
