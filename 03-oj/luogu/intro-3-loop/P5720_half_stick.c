/*
 * P5720_half_stick.c —— 一尺之棰：每天砍一半（向下取整），第几天长度变成 1
 * 来源：洛谷 P5720 【深基4.例4】一尺之棰
 * 题目：https://www.luogu.com.cn/problem/P5720
 * 日期：2026-10-24
 * 思路：1) 题目问「第几天长度变成 1」，而第一天就是 a 本身，
 *          所以 天数 = 砍的次数 + 1。
 *       2) 砍几次事先不知道，只知道「一直砍到 1 为止」—— 这就是 while 的典型形状。
 *       3) 整数除法 a / 2 自动向下取整，正好是题目要的「砍一半」。
 *       4) a = 1 时一次都不砍，count 是 0，输出 1 正好对 —— 所以别改成 do-while。
 * 要点：第一天是 a 本身，从第二天才开始砍，所以砍的次数 +1 就是答案。
 *       while (a != 1) 每轮 a = a / 2（整数除法自动向下取整）、count++，
 *       循环结束时 count 是「砍了几下」，加 1 才是「第几天」。
 *       数据 1 ≤ a ≤ 10^9，最多砍约 30 次，while 完全跑得动。
 * 建议：注意 a = 1 时循环一次都不进，count 还是 0，输出 1 —— 这是对的，
 *       别为了「至少砍一次」改成 do-while，那会多算一天。
 *       #include <math.h> 本题用不上，可以删掉（留着也无害，但项目里用不到的头文件最好别留）。
 */
#include <stdio.h>
int main()
{
    int a, count = 0;
    scanf("%d", &a);
    while (a != 1)
    {
        a = a / 2;
        count++;
    }
    printf("%d", count + 1);
    return 0;
}
