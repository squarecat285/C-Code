/*
 * P1075_prime_factorization.c —— 质因数分解：n 是两个不同质数之积，求较大的那个
 * 来源：洛谷 P1075 [NOIP 2012 普及组] 质因数分解
 * 题目：https://www.luogu.com.cn/problem/P1075
 * 日期：2026-10-31
 * 思路：1) n 只有一对因子（两个不同质数 p、q 且 p < q），题目要的是大的 q = n / p，
 *          所以问题变成「找出小的那个质数 p」。
 *       2) p 一定不超过 √n —— 只要有一个因子比 √n 大，另一个就比 √n 小。
 *       3) 于是从 2 往上试，第一个能整除 n 的 i 就是 p；条件写 i * i < n，
 *          等价于 i < √n，还省掉每次开方。
 *       4) 找到就直接 printf(n / i) 然后 break —— 只可能有一个答案。
 * 要点：n 到 2×10^9，i * i 最大也就 2×10^9 量级，用 long long 存 n 和 i 都不会溢出。
 * 坑：末尾那句注释「不能直接 i = i + 2」是对的 —— 从 2 开始每次加 2 只试偶数，
 *     把 3、5、7 这些全跳过了。真想省一半，得先单独判 n % 2 == 0，再从 3 开始每次 +2。
 * 建议：这题是「找最小因子」的原型。判质数、分解质因数、枚举约数，
 *       骨架都是「试到 √n 就够」—— 因为因子成对出现，一个在 √n 这边，一个在那边。
 */
#include <stdio.h>
int main()
{
    long long n;
    scanf("%lld", &n);
    for (long long i = 2; i * i < n; i++)
    {
        if (n % i == 0)
        {
            printf("%lld", n / i);
            break;
        }
    }
    return 0;
}
