/*
 * P5722_series_sum.c —— 数列求和：算 1 + 2 + … + n，题目不许用公式
 * 来源：洛谷 P5722 【深基4.例11】数列求和
 * 题目：https://www.luogu.com.cn/problem/P5722
 * 日期：2026-10-26
 * 思路：1) n ≤ 100 时高斯那个 n(n+1)/2 一行就出答案，但题目明确不许用，
 *          那就退回最朴素的做法：把这一串数一个一个加过去。
 *       2) 「一个一个」= 循环：需要一个变量从 1 走到 n，这就是 i。
 *       3) 累加需要一个「筐」来存已经加好的部分，这就是 sum。
 *       4) 循环体只有一件事：把当前的 i 扔进筐里 —— sum += i。
 * 要点：sum 的初值必须是 0 —— 还没加任何东西时，部分和就是 0（加法的单位元）。
 *       n = 100 时答案是 5050，int 远远够。
 * 坑：sum 忘了写 = 0 就会拿到栈上的垃圾值，每次运行结果都不一样。
 *     这类「初始化」漏写，编译器不一定警告，但结果一定不可信。
 */
#include <stdio.h>
int main()
{
    int n;
    int sum = 0;
    scanf("%d", &n);
    for (int i = 1; i <= n; i++)
    {
        sum += i;
    }
    printf("%d", sum);
    return 0;
}
