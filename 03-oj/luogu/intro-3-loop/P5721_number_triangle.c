/*
 * P5721_number_triangle.c —— 数字直角三角形：从 1 开始斜着填充，第一个直角边就是 1
 * 来源：洛谷 P5721 【深基4.例6】数字直角三角形
 * 题目：https://www.luogu.com.cn/problem/P5721
 * 日期：2026-10-24
 * 思路：1) 输出是个三角形，先把两个维度分清楚：打几行（外层）、每行打几个（内层）。
 *       2) 每行的个数在变：第 1 行 n 个、第 2 行 n-1 个……第 i 行 n-i+1 个。
 *          n 很小（≤ 13），按个数直接算就行，不用推公式。
 *       3) 填的数字从 1 开始一路往上加、不随换行重置 ——
 *          所以 num 必须声明在两层循环的外面。
 *       4) 每个数固定两位、不足补 0，用 %02d。
 * 要点：外层 i 管第几行，内层管这一行打几个数 —— 第 1 行 n 个、第 2 行 n-1 个，
 *       所以写 j = n; j >= i; j-- 正好是 n-i+1 次。
 *       num 声明在两层循环外面，跨行累加，才会 01 02 … 一直到最后一个数。
 *       %02d 是「最少 2 位、不够前面补 0」，格式串里 % 和 02 顺序不能反。
 *       数据 1 ≤ n ≤ 13，所以最多打到 91，两位够用。
 * 建议：内层写成 for (int j = 1; j <= n - i + 1; j++) 更直白（「这一行要打几个」），
 *       现在这种 n 递减到 i 的写法也能读，就是要在脑子里换算一次。
 */
#include <stdio.h>
int main()
{
    int n;
    scanf("%d", &n);
    int num = 1;
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <=n-i+1; j++)
        {
            printf("%02d", num);
            num++;
        }
        printf("\n");
    }
    return 0;
}
