/*
 * P5724_range.c —— 求极差：n 个整数里最大值减去最小值
 * 来源：洛谷 P5724 【深基4.习5】求极差
 * 题目：https://www.luogu.com.cn/problem/P5724
 * 日期：2026-10-31
 * 思路：1) 极差只要两个数：最大值和最小值，所以不用排序、也不用数组。
 *       2) 边读边更新：每读进一个 a，就和当前 max、min 各比一次。
 *       3) 初值取「数据不可能越过的那条线」：题目保证 0 ≤ a ≤ 1000，
 *          所以 max 从 0 起步、min 从 1000 起步，第一个数一定能把它们顶到位。
 * 要点：数据范围已知时，直接拿范围的端点当哨兵初值，比写 IF 判断第一次更省事。
 * 坑：max = 0、min = 1000 是「刚好卡在边界上」的写法，靠的是数据范围不变。
 *     一旦题目改成 1 ≤ a ≤ 10^9，或者允许负数，这两个初值立刻失效。
 * 建议：更稳的写法是先读第一个数，拿它同时当 max 和 min，后面的数再进来比 ——
 *       这样和数据范围彻底解耦。P5726 用 -1 / 11 是同一个套路的同一种风险。
 */
#include <stdio.h>
int main()
{
    int n;
    scanf("%d", &n);
    int max = 0;
    int min = 1000;
    for (int i = 0; i < n; i++)
    {
        int a;

        scanf("%d", &a);
        if (a > max)
            max = a;
        if (a < min)
            min = a;
    }
    printf("%d", max - min);
    return 0;
}
