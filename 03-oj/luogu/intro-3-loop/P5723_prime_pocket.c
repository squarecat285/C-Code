/*
 * P5723_prime_pocket.c —— 质数口袋：从 2 开始往口袋里装质数，装进去的总和不能超过 L
 * 来源：洛谷 P5723 【深基4.习9】质数口袋
 * 题目：https://www.luogu.com.cn/problem/P5723
 * 日期：2026-10-26
 * 思路：1) 要装的东西有两个条件：①它得是质数 ②装进去之后总和不能超过 L。
 *          两个条件能各自单独判，所以代码也拆成两段：先判质数，再判能不能装。
 *       2) 为什么从小到大试就行？质数按从小到大排，先装小的，装得进的数量最多。
 *          所以 i 从 2 开始一个一个往上试，不用排序、不用筛。
 *       3) 判质数只要试除到 √i：若 i = a × b 且 a ≤ b，那 a ≤ √i；
 *          反过来，2..√i 里一个因子都没有，i 就一定是质数。
 *          写成 j * j <= i，不用调 sqrt，也没有浮点误差。
 *       4) sum 一超过 L 就停：后面的质数只会更大，越往后越装不下，不会有转机。
 *          所以 i 的上界根本不用写死，条件就写成 for (int i = 2;; i++)。
 * 要点：count 数装进去几个，sum 记和；每装一个就 printf 一行，最后单独打 count。
 * 坑：1) break 写在了 if 外面 —— 内层循环第一次 j = 2 就退出，
 *          等于只检查了「能不能被 2 整除」，所有奇数都被当成了质数。
 *          L = 100 正确装 9 个，那样会装出 50 个。
 *       2) 一开始把循环写成 i <= L，那是「每个质数都不超过 L」，
 *          不是「累加和不超过 L」。L = 9 正确是 2、3（和 5），会输成 2 3 5 7 9。
 */
#include <stdio.h>
int main()
{
    int L;
    int count = 0;
    int sum = 0;
    scanf("%d", &L);
    for (int i = 2;; i++)
    {
        int first = 1;
        for (int j = 2; j * j <= i; j++)
        {
            if (i % j == 0)
            {
                first = 0;
                break;
            }
        }
        if (first == 1)
        {
            if (sum + i > L)
                break;
            sum += i;
            printf("%d\n", i);
            count++;
        }
    }
    printf("%d", count);
    return 0;
}
