/*
 * P1423_xiaoyu_swimming.c —— 小玉在游泳：每步是上一步的 98%，问几步能累计游到 s 米
 * 来源：洛谷 P1423 小玉在游泳
 * 题目：https://www.luogu.com.cn/problem/P1423
 * 日期：2026-10-29
 * 思路：1) 每步游的距离是等比数列：2，2 × 0.98，2 × 0.98²，……
 *       2) 问「第几步刚好累计到 s」，这个没法一步算出来，只能边加边看：
 *          sum += 这一步的长度，然后判 sum >= s。
 *       3) 步数事先不知道，循环就写成「一直算下去」；i 从 1 开始，
 *          因为加完第一次就是第 1 步。
 *       4) 衰减放在加完之后：先加上「这一步游的」，再算「下一步还能游多少」。
 * 要点：等比数列求和收敛到 2 / (1 − 0.98) = 100 米，所以 s < 100 一定有解；
 *       s 越接近 100 步数越多，s = 99.9 时要游 342 步。
 * 坑：数据允许 s = 0（0 ≤ s < 100）。你现在会输出 1，
 *     而按「一步都不用游」理解应该是 0。若交上去在某个点 WA，多半就是这个点，
 *     加一句 if (s == 0) { printf("0"); return 0; } 即可。
 */
#include <stdio.h>
int main()
{
    double n = 2.0;
    int i;
    double sum = 0.0;
    double s;
    scanf("%lf", &s);
    for (i = 1;; i++)
    {

        sum = sum + n;
        n = n * 0.98;
        if (sum >= s)
        {
            printf("%d", i);
            break;
        }
    }
    return 0;
}
