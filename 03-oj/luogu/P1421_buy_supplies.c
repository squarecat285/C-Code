/*
 * P1421_buy_supplies.c —— 小玉买文具：a 元 b 角最多能买几支 1 元 9 角的笔
 * 来源：洛谷 P1421 小玉买文具
 * 题目：https://www.luogu.com.cn/problem/P1421
 * 结果：✅ AC
 * 日期：2026-10-17
 * 要点：元、角不能并存，先全部化成角：手上的钱 = a * 10 + b，一支笔 = 19 角；
 *       整除自动向下取整，问「最多买几支」时正好是想要的结果。
 * 坑：没有踩坑，一次就对了 —— 这题的关键全在「单位统一」上，
 *     19 就是 1 元 9 角换成角之后的数，别当成魔法数字。
 */
#include <stdio.h>
int main()
{
    int a, b;
    scanf("%d %d", &a, &b);
    int pens = (a * 10 + b) / 19; /* 1 元 9 角 = 19 角 */
    printf("%d", pens);
    return 0;
}
