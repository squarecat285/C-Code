/*
 * P1425_fish_swim.c —— 小鱼的游泳时间：从 a 时 b 分游到 c 时 d 分，一共游了多久
 * 来源：洛谷 P1425 小鱼的游泳时间
 * 题目：https://www.luogu.com.cn/problem/P1425
 * 结果：✅ AC
 * 日期：2026-10-17
 * 要点：小时和分钟分开减，分钟不够减就向小时借 1（f += 60; e -= 1），
 *       就是手算减法的竖式；题目说「当天的」，所以保证同一天、结束晚于开始，不用管跨天。
 * 坑：借位这种写法有个理论瑕疵 —— 要是分钟输入成 60，会打出「1 小时 60 分」没归一化
 *     （实测 1,124,250 组合法时刻全对，那 325 组反例全是分钟 = 60，真数据不会出现）。
 *     更省事的写法是把时间全部换算成「一共多少分钟」：
 *     total = (c * 60 + d) - (a * 60 + b); 然后 total / 60 和 total % 60，不用 if。
 */
#include <stdio.h>
int main()
{
    int a, b, c, d;
    scanf("%d %d %d %d", &a, &b, &c, &d);
    int e = c - a;
    int f = d - b;
    if (f < 0)
    {
        f = f + 60;
        e = e - 1;
    }
    printf("%d %d", e, f);
    return 0;
}
