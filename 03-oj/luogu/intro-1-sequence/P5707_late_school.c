/*
 * P5707_late_school.c —— 上学迟到：算最晚几点出门才能 8:00 到校
 * 来源：洛谷 P5707 【深基2.例12】上学迟到
 * 题目：https://www.luogu.com.cn/problem/P5707
 * 日期：2026-10-17
 * 思路：1) 「几点几分」没法直接减，跨零点就出负数。先把时间统一成
 *          「从 0:00 起的第几分钟」：8:00 = 480 分钟。
 *       2) 路上要几分钟？走路 s 米、每分钟 v 米，除不尽也得走完整的一分钟 ——
 *          向上取整 (s + v - 1) / v（题干「只能在每分钟第 0 秒出发」就是这个意思），
 *          再加 10 分钟垃圾分类。
 *       3) 出发时刻 = 480 − 提前量。可能是负数，说明是前一天，加 1440 分钟绕回来。
 *       4) 最后 t / 60 得小时、t % 60 得分钟，用 %02d 补足两位。
 * 要点：时间统一换算成「从 0:00 起第几分钟」再算，8:00 就是 480；
 *       走路分钟用 (s + v - 1) / v 向上取整（只能整分出发，1.01 分钟也得留 2 分钟）；
 *       提前量 = 走路 + 10（垃圾分类）；最后 t / 60 得「时」、t % 60 得「分」，%02d 补零。
 * 坑：1) 整数除法 s / v 是向下取整，直接写得 1 分钟会少算 1 分钟，8:00 到不了；
 *     2) t 为负数表示前一天出发 —— 一开始只 +1440 一次，提前量超过一整天
 *        （如 s=10000, v=1）就会输出 -134:-50；已改成 while (t < 0) t += 1440;
 */
#include <stdio.h>
int main()
{
    int s, v;
    scanf("%d %d", &s, &v);
    int walk = (s + v - 1) / v + 10;
    int t = 480 - walk;
    if (t >= 0)
    {
        int t_h = t / 60;
        int t_m = t % 60;
        printf("%02d:%02d", t_h, t_m);
    }
    else
    {
        while (t < 0)
        {
            t = t + 1440;
        }
        int t_h = t / 60;
        int t_m = t % 60;
        printf("%02d:%02d", t_h, t_m);
    }
    return 0;
}
