/*
 * P1000_mario.c —— 超级玛丽游戏：用字符画原样输出题面给的那幅图
 * 来源：洛谷 P1000 超级玛丽游戏
 * 题目：https://www.luogu.com.cn/problem/P1000
 * 日期：2026-10-17
 * 思路：1) 这题没有算法，全是输出，难点只在「一个字符都不能差」。
 *       2) 所以思路不是算，是抄：把题面给的样例原样搬进代码，一行一个 printf。
 *       3) 换行写在格式串里（"\n"），绝不能写成一个真正的回车 ——
 *          字符串里出现真换行，引号会被提前断开，编译器直接报 missing terminating "。
 * 要点：这题一个数都不用算，就是把图一字不差地打出来；
 *       每一行单独一个 printf("...\n"); 锁死，别让换行拆到字符串外面去。
 * 坑：1) 一开始把 \n 和真正的回车混着写，字符串字面量被拆成好几行，
 *        编译都过不去（"missing terminating \" character"）。
 *     2) 画里行首和行中间的空格全是有效字符，少一个、多一个都 WA。
 */
#include <stdio.h>
int main()
{
    printf("                ********\n");
    printf("               ************\n");
    printf("               ####....#.\n");
    printf("             #..###.....##....\n");
    printf("             ###.......######              ###            ###\n");
    printf("                ...........               #...#          #...#\n");
    printf("               ##*#######                 #.#.#          #.#.#\n");
    printf("            ####*******######             #.#.#          #.#.#\n");
    printf("           ...#***.****.*###....          #...#          #...#\n");
    printf("           ....**********##.....           ###            ###\n");
    printf("           ....****    *****....\n");
    printf("             ####        ####\n");
    printf("           ######        ######\n");
    printf("##############################################################\n");
    printf("#...#......#.##...#......#.##...#......#.##------------------#\n");
    printf("###########################################------------------#\n");
    printf("#..#....#....##..#....#....##..#....#....#####################\n");
    printf("##########################################    #----------#\n");
    printf("#.....#......##.....#......##.....#......#    #----------#\n");
    printf("##########################################    #----------#\n");
    printf("#.#..#....#..##.#..#....#..##.#..#....#..#    #----------#\n");
    printf("##########################################    ############\n");
    return 0;
}
